#!/usr/bin/env python3
"""Generate committed C++ frame vectors using the canonical Python KLF codec."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "krakenlink"))
from krakenlink.proto.frame import Frame, encode_frame, cobs_encode

VECTORS = [
    Frame(0x01, 0x1234, b"\x00\x01\x02\x00"),
    Frame(0x7F, 0, bytes(range(22))),
    Frame(0x20, 0xFFFF, b"KLF"),
]

def render() -> str:
    lines = ["// Generated by tools/gen_vectors.py; do not edit.", "#pragma once", "#include <stdint.h>"]
    for i, frame in enumerate(VECTORS):
        raw = encode_frame(frame)
        encoded = cobs_encode(raw)
        for suffix, data in (("frame", raw), ("cobs", encoded)):
            values = ", ".join(f"0x{x:02X}" for x in data)
            lines.append(f"static const uint8_t vector_{suffix}_{i}[] = {{{values}}};")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "test/test_klf/vectors.h"
    target.write_text(render())
    print(target)
